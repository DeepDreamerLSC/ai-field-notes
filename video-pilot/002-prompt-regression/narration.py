#!/usr/bin/env python3
"""第二条样片旁白：复用首条生成器，逐句指定语速与停顿。"""
import asyncio
import importlib.util
from pathlib import Path

BASE = Path(__file__).parent
spec = importlib.util.spec_from_file_location(
    "video001_narration", BASE.parent / "001-customer-agent-three-questions" / "narration.py")
shared = importlib.util.module_from_spec(spec)
spec.loader.exec_module(shared)

SENTENCES = [
    "AI 把错题改对了，你会放心换新版吗？",
    "先别急。另一条原本正确的，可能反而错了。",
    "看个合成例子：让 AI 从订单备注里，找出要付的钱。结果只是演示。",
    "合计一百二十，优惠二十，应付一百。旧版却取了一百二十。",
    "这条里，钱恰好写在最后。你试着补一句：取最后一个数字。",
    "重跑得到一百，看起来修好了。可另一条是实付八十，订单尾号二零二四。",
    "新版把尾号当金额，八十变成二零二四。最后的数字，不一定是要付的钱。",
    "原本答对的，现在错了。修好一题的证据，不够支持换新版。",
    "只验证用来改提示词的题，就容易把局部修好，误当成整体变好。",
    "先留住这次的错题，检查旧问题有没有修好。",
    "再留住原本答对的题，检查有没有被这次改动弄坏。",
    "最后留几条没参与改稿的题，检查是不是只适配了眼前这几条。",
    "留出题一旦用来继续改稿，就补新题，别再当作没见过。",
    "这个例子，修复通过，保护失败，留出未测。本版退回。",
    "即使三组都过，也只说明这些题过关。偶发错误要重复跑，关键任务扩大覆盖。",
    "下次改动前，一张表保存输入、预期答案，以及怎么算通过。",
    "同一批题，前后各跑一次。一次只改一项，才知道变化来自哪里。",
    "发现新的失败，加入下次的保护清单。",
    "换新版前，拿出三份证据：旧错修好了，原来对的没变坏，还有没见过的题。",
    "先保存这张检查卡，下一次改提示词就能用。"
]

GAPS = [0.2, 0.85, 0.25, 0.35, 0.2, 0.25, 0.7, 0.75, 0.25, 0.35, 0.35, 0.3, 0.45, 0.55, 0.4, 0.25, 0.3, 0.45, 0.65, 0.0]
RATES = ['+6%', '+6%', '+6%', '+6%', '+6%', '+6%', '+6%', '+0%', '+6%', '+6%', '+6%', '+6%', '+6%', '+6%', '+6%', '+6%', '+6%', '+6%', '+0%', '+6%']
TAIL = 2.6


async def main() -> None:
    await shared.generate(BASE, SENTENCES, gaps=GAPS, rates=RATES, tail=TAIL)


if __name__ == "__main__":
    asyncio.run(main())
