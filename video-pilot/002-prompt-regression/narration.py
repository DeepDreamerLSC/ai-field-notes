spec = importlib.util.spec_from_file_location(
    "video001_narration", BASE.parent / "001-customer-agent-three-questions" / "narration.py")
shared = importlib.util.module_from_spec(spec)
spec.loader.exec_module(shared)

SENTENCES = [
    "改了提示词，AI 提取对了一条订单的金额。就能换上新提示词吗？",
    "先别急。新提示词可能让另一条订单的金额，从提取正确变成错误。",
    "看个例子：让 AI 从订单备注里，找出要付的钱。",
    "合计一百二十，优惠二十，应付一百。旧提示词让 AI 错取了一百二十。",
    "应付金额恰好写在最后。你补一句提示词：取最后一个数字。",
    "改完输出一百，金额对了。另一条订单是实付八十，订单尾号二零二四。",
    "AI 把尾号当成金额，输出二零二四。最后的数字，不一定是要付的钱。",
    "另一条订单原本提取正确，现在错了。修好一条，还不能换上新提示词。",
    "只检查用来改提示词的订单，会漏掉其他订单的新错误。",
    "先存下原来提取错的订单，检查旧错误有没有修好。",
    "再存下原来提取对的订单，检查正确金额有没有被改错。",
    "再留几条没用来改提示词的订单，检查 AI 能不能提取正确。",
    "看了结果又改提示词，就补新订单，别再当作没见过。",
    "旧错误修好了，原来对的却错了，新订单还没测。先别换提示词。",
    "都提取对，也只证明这些订单通过。偶发错误重复测，重要业务多测几种情况。",
    "改提示词前，保存订单原文、正确金额，写清怎么算提取正确。",
    "让新旧提示词处理同一批订单。一次只改一项，才方便判断变化来自哪里。",
    "新发现的错误订单，加入下次检查清单。",
    "换提示词前，确认：旧错修好了，原来对的没变错，没用过的订单也测了。",
    "保存这张检查卡，下次改提示词前照着检查。"
]

GAPS = [0.5, 1.4, 0.35, 0.7, 0.55, 0.75, 1.1, 1.0, 0.35, 0.5, 0.5, 0.5, 0.6, 1.0, 0.6, 0.5, 0.5, 0.6, 0.85, 0.0]
